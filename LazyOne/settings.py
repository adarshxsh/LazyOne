# Firebase Admin SDK (for backend)
# Local: FIREBASE_SERVICE_ACCOUNT_KEY_PATH=path/to/key.json (gitignored).
# Vercel: FIREBASE_SERVICE_ACCOUNT_JSON=<the key JSON, raw or base64> as a secret env var.
